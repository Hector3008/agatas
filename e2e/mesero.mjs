import { chromium } from "playwright";
import { preparar, P } from "../test/ayudas.js";
const SH = "./capturas";
const e = await preparar();
const base = e.url.replace(/\/agatas$/, "");
const ana = await e.jugador("Ana", { colores: ["verde","cafe","rojo","verde","cafe","rojo"] });
const r = await ana.cli.post(`${P}/premios`, { premioId: "p3" });
const canje = r.body.codigoCanjeTexto ?? r.body.codigoCanje;
console.log("RECLAMO", r.status, canje);
const br = await chromium.launch();
const ctx = await br.newContext({ viewport:{width:390,height:800}, extraHTTPHeaders:{ "x-user":"mesero" } });
const m = await ctx.newPage();
m.on("pageerror", x=>console.log("PAGEERR", x.message)); m.on("console", x=>{ if(x.type()==="error") console.log("CONSOLE", x.text()); });
await m.goto(`${base}/agatas/app/?m=mesero`);
await m.getByRole("tab",{name:"Premios"}).click();
await m.getByText("3 stickers").waitFor();
await m.screenshot({ path: `${SH}/Mesero-lista.png` });
await m.getByRole("tab",{name:"Canjear"}).click();
await m.locator("#canje").fill(String(canje).toLowerCase());
await m.getByRole("button",{name:"Buscar"}).click();
await m.getByText("Pendiente de entregar").waitFor();
await m.screenshot({ path: `${SH}/Mesero-resultado.png` });
await m.getByRole("button",{name:"Entregar premio"}).click();
await m.getByText("Listo: premio entregado.").waitFor();
await m.screenshot({ path: `${SH}/Mesero-entregado.png` });
// segundo intento: ya entregado
await m.getByRole("button",{name:"Canjear otro código"}).click();
await m.locator("#canje").fill("ZZZZ9999");
await m.getByRole("button",{name:"Buscar"}).click();
await m.getByText("Ese código no existe").waitFor();
await m.getByRole("tab",{name:"Jugadores"}).click();
await m.getByText("Ana").waitFor();
await m.screenshot({ path: `${SH}/Mesero-jugadores.png` });
console.log("ESTADO PR:", e.docs("premio").map(d=>d.estado));
// sin sesión
const c2 = await br.newContext({ viewport:{width:390,height:800}, colorScheme:"dark" });
const s = await c2.newPage();
await s.goto(`${base}/agatas/app/?m=mesero`);
await s.locator("#canje").fill("ABCD2345"); await s.getByRole("button",{name:"Buscar"}).click();
await s.getByText("Entra a tu cuenta").waitFor();
await s.screenshot({ path: `${SH}/Mesero-sinsesion.png` });
console.log("OK");
await br.close(); await e.cerrar();
